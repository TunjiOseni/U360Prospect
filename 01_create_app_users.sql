CREATE TABLE U360PROSPECT.APP_USERS
(
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    WINDOWS_USERNAME VARCHAR2(256) NOT NULL,
    DISPLAY_NAME VARCHAR2(200),
    IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_BY VARCHAR2(256),
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY VARCHAR2(256),
    UPDATED_AT TIMESTAMP(6),
    LAST_LOGIN_DATE TIMESTAMP(6),
    DISABLED_DATE TIMESTAMP(6),
    DISABLED_REASON VARCHAR2(500),
    CONSTRAINT CK_APP_USERS_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N')),
    CONSTRAINT PK_APP_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_APP_USERS_USERNAME UNIQUE (WINDOWS_USERNAME)
)
TABLESPACE USERS;
